# ----------------- Cosine similarity -----------------

def cosine_similarity(a: List[float], b: List[float]) -> float:
    """Cosine similarity. Returns dot product since inputs are L2-normalised."""
    if len(a) != len(b):
        return 0.0
    return sum(x * y for x, y in zip(a, b))


# ----------------- In-memory vector index -----------------

class VectorIndex:
    """In-memory vector index with cosine top-k search.

    Production replaces with pgvector wrapper. Interface required:
      add(item_id, vector, metadata)
      search(query_vector, top_k, threshold) -> list of {item_id, similarity, metadata}
      size()
      clear()
    """

    def __init__(self) -> None:
        self._items: Dict[str, Tuple[List[float], Dict[str, Any]]] = {}

    def add(self, item_id: str, vector: List[float], metadata: Optional[Dict[str, Any]] = None) -> None:
        self._items[item_id] = (vector, metadata or {})

    def remove(self, item_id: str) -> None:
        self._items.pop(item_id, None)

    def size(self) -> int:
        return len(self._items)

    def clear(self) -> None:
        self._items.clear()

    def search(
        self,
        query: List[float],
        top_k: int = 5,
        threshold: float = 0.0,
    ) -> List[Dict[str, Any]]:
        if not self._items:
            return []
        scored = [
            {
                "item_id": iid,
                "similarity": cosine_similarity(query, vec),
                "metadata": meta,
            }
            for iid, (vec, meta) in self._items.items()
        ]
        scored = [s for s in scored if s["similarity"] >= threshold]
        scored.sort(key=lambda s: s["similarity"], reverse=True)
        return scored[:top_k]


