def features_to_text(features: Dict[str, Any], stable_keys: Optional[Tuple[str, ...]] = None) -> str:
    """Convert a feature dict to a deterministic text representation for embedding.

    Keys are sorted (or use stable_keys order) so the same features always
    produce the same input string -> same vector via hash embedding.
    """
    if stable_keys:
        ordered = [(k, features.get(k)) for k in stable_keys if features.get(k) is not None]
    else:
        ordered = sorted(
            ((k, v) for k, v in features.items() if v is not None),
            key=lambda kv: kv[0],
        )
    return json.dumps(ordered, default=str)


def cohort_signature(item_ids: List[str], top_similarity: float) -> str:
    """Audit signature over a similarity-search result. Deterministic."""
    sig_input = "|".join(sorted(item_ids)) + f"|{top_similarity:.4f}"
    return hashlib.sha256(sig_input.encode()).hexdigest()
