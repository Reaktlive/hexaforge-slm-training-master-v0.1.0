def hash_to_floats(text: str, dim: int = DEFAULT_EMBED_DIM) -> List[float]:
    """Deterministic hash-based embedding.

    Same text -> same L2-normalised vector. Not semantically meaningful —
    intended for tests, demos, and air-gapped fallback. Production swaps in
    a real embedding provider via the EmbeddingProvider interface.
    """
    out: List[float] = []
    seed = text.encode("utf-8")
    counter = 0
    while len(out) < dim:
        block = hashlib.sha256(seed + counter.to_bytes(4, "big")).digest()
        for i in range(0, len(block), 2):
            if len(out) >= dim:
                break
            raw = int.from_bytes(block[i:i + 2], "big", signed=False)
            out.append((raw / 65535.0) * 2.0 - 1.0)
        counter += 1
    norm = math.sqrt(sum(x * x for x in out)) or 1.0
    return [x / norm for x in out]


async def hash_embedding_provider(text: str) -> Tuple[List[float], Dict[str, Any]]:
    """Default async embedding provider — hash-based, deterministic."""
