def action_tenant(action: Any) -> str:
    """The action's tenant, normalised. Empty string when absent/blank."""
    if not isinstance(action, dict):
        return ""
    for key in _TENANT_KEYS:
        val = action.get(key)
        if val is None or isinstance(val, (dict, list)):
            continue
        canon = canonical_identity(val)
        if canon:
            return canon
    return ""


def canonical_action_ref(action: Any) -> str:
    """The stable, CONTENT-BOUND id an approval is cryptographically pinned to.

    Fas 2.22 (external DD, Peter #1): the ref is a SHA-256 over the immutable
    semantic content of the action — the exact fields that decide WHAT will
    happen (selected_action, target_asset, action_parameters, policy_requirements,
    tenant, tier, idempotency_key) — NOT a mutable correlation id (request_id).
    Because the approval signature binds this ref (see _canonical_approval_msg),
    changing ANY of those fields after an approval was issued changes the ref and
    breaks every signature: a valid approval for one action body can never be
    replayed onto a different body (the confused-deputy hole). An action carrying
    NONE of these fields yields "" (fail-closed: an unidentified action cannot be
    approved). The hash is computed over a canonical JSON (sorted keys, tight
    separators) so it is deterministic across processes and re-serialisations."""
    if not isinstance(action, dict):
        return ""
    core = {k: action[k] for k in _CANONICAL_ACTION_FIELDS if action.get(k) is not None}
    # Fas 3.2 — bind the tenant under ONE canonical key regardless of which name
    # the caller used, so the hash cannot be dodged by a rename upstream.
    tenant = action_tenant(action)
    if tenant:
        core["tenant_id"] = tenant
    if not core:
        return ""  # no semantic content to bind — fail closed
    canonical = json.dumps(core, sort_keys=True, separators=(",", ":"), default=str)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


def _action_ref(action: Any) -> str:
    """The stable id an approval must be bound to (anti confused-deputy /
    cross-action replay). Fas 2.22: this is now the CONTENT-bound
    canonical_action_ref (a hash over the action's immutable semantic fields),
    NOT a request_id. Unidentified action => "" => nothing can approve it."""
    return canonical_action_ref(action)


def _canonical_approval_msg(action_ref: str, approver: str, role: str, nonce: str, expires_at: Any = None) -> bytes:
    """The exact bytes the approval backend signs — binds approver + role + THIS
    action + a fresh nonce so a signature cannot be replayed onto another action.
    Fas 2.17: when the backend issues an expiry, expires_at is PART of the signed
    bytes — stripping or altering it breaks the signature (str(expires_at)
    verbatim as sent). Approvals without expiry keep the 4-field format."""
    # Fas 3.11 — the SIGNED bytes bind the canonical spelling, so a signature
    # issued for "Alice " cannot be presented as a second, different approver.
    base = "%s|%s|%s|%s" % (action_ref, canonical_identity(approver),
                            canonical_identity(role), nonce)
    if expires_at is not None and str(expires_at) != "":
        base = base + "|" + str(expires_at)
    return base.encode("utf-8")


# Fas 3.7 (adversarial finding) — APPROVAL SOVEREIGNTY.
# With a shared HMAC secret the party that VERIFIES an approval can also MINT
# one: the key sits in the agent's own environment, so a compromised agent
# process (or anyone who can read its env) can sign "two independent approvals"
# for its own tier_4 action. Demonstrated on a real bundle: dual_approval
# returned "approved" for approvals minted inside the agent. That defeats
# separation of duties, which is the entire point of the tier ladder.
#
# The fix is asymmetric: the APPROVER signs with a private key that never exists
# on this host, and the agent verifies with a PUBLIC key. Then the agent
# structurally cannot mint what it checks.
#
#   CCAS_APPROVAL_PUBKEYS  JSON {"<approver_principal>": "<base64 ed25519 pub>"}
#                          (or a single base64 key used for every approver)
#
# When pubkeys are bound, the HMAC path is REFUSED — a fallback that a caller
# can select is not a fallback, it is the hole. When they are not bound, HMAC
# still works (dev/legacy) but every decision DISCLOSES that its approvals are
# self-mintable, so the artifact never claims a property it does not have.
CCAS_APPROVAL_PUBKEYS = os.environ.get("CCAS_APPROVAL_PUBKEYS", "")


def _approval_pubkey_map():
    raw = CCAS_APPROVAL_PUBKEYS.strip()
    if not raw:
        return {}
    try:
        data = json.loads(raw)
    except (ValueError, TypeError):
        return {"*": raw}  # a bare key string applies to every approver
    if isinstance(data, dict):
        return {str(k): str(v) for k, v in data.items()}
    return {}


# Fas 3.13 — tolerance for legitimate backward clock steps (NTP correction,
# VM resume). An attacker rolling the clock back to revive an expired approval
# needs minutes-to-hours, not seconds, so a small window costs nothing. It IS a
# boundary: approvals whose lifetime is shorter than this window cannot be
# protected by the ratchet, which is why it is named, defaulted conservatively
# and settable rather than hidden inside a comparison.
CCAS_CLOCK_SKEW_TOLERANCE_S = float(os.environ.get("CCAS_CLOCK_SKEW_TOLERANCE_S", "120") or 120)


def clock_trust() -> str:
    """Whether the local clock can be trusted to judge approval freshness.

    "monotonic_ok"      - the clock is at or ahead of every timestamp the
                          append-only approval ledger has ever recorded.
    "rollback_detected" - the clock reads BEFORE the ledger's high-water mark
                          by more than the skew tolerance. Something moved time
                          backwards; expiry checks are meaningless and the gate
                          must not release.
    "no_high_water"     - the ledger has recorded nothing yet, so there is no
                          floor to compare against. Rollback is UNDETECTABLE
                          here. Disclosed, never assumed away.
    "ledger_unreadable" - the floor cannot be established at all.
    """
    try:
        floor = approval_ledger.high_water_ts()
    except Exception:  # noqa: BLE001
        return "ledger_unreadable"
    if not floor:
        return "no_high_water"
    if time.time() + CCAS_CLOCK_SKEW_TOLERANCE_S < floor:
        return "rollback_detected"
    return "monotonic_ok"


def approval_trust() -> str:
    """How much an approval is worth on THIS deployment. Reported in every
    decision so the posture is never implicit."""
    if _approval_pubkey_map():
        return "asymmetric"
    if CCAS_APPROVAL_KEY:
        return "shared_secret_self_mintable"
    return "unbound"


def _ed25519_ok(pub_b64: str, signature: str, msg: bytes) -> bool:
    """Verify with the bundle's OWN audited pure-python Ed25519 (emitted as a
    shared runtime module), so neither a root CLI script nor a new dependency
    enters the runtime import graph."""
    try:
        import base64 as _b64

        from src.shared.ed25519_verify import ed25519_verify as _verify
        try:
            sig = bytes.fromhex(signature)
        except ValueError:
            sig = _b64.b64decode(signature)
        return bool(_verify(_b64.b64decode(pub_b64), sig, msg))
    except Exception:  # noqa: BLE001 - any failure is a failed verification
        return False


def verify_approval_signature(approval: Any, action_ref: str) -> bool:
    """CUSTOMER_SLOT — prove the approval was issued by the customer's approval
    backend. PREFERRED: Ed25519 against CCAS_APPROVAL_PUBKEYS (the agent holds
    no private key and therefore cannot mint). FALLBACK: HMAC-SHA256 with
    CCAS_APPROVAL_KEY, accepted ONLY when no pubkeys are bound and disclosed as
    self-mintable. FAIL-CLOSED: with neither bound this returns False, so the
    default package approves nothing."""
    if not isinstance(approval, dict):
        return False
    sig = approval.get("signature")
    if not isinstance(sig, str) or not sig:
        return False
    pubkeys = _approval_pubkey_map()
    if pubkeys:
        approver = str(approval.get("approver_principal") or "")
        role = str(approval.get("role") or "")
        nonce = str(approval.get("nonce") or "")
        pub = pubkeys.get(approver) or pubkeys.get("*")
        if not pub:
            return False  # an approver with no registered key approves nothing
        return _ed25519_ok(
            pub, sig,
            _canonical_approval_msg(action_ref, approver, role, nonce, approval.get("expires_at")),
        )
    if not CCAS_APPROVAL_KEY:
        return False
    sig = approval.get("signature")
    if not isinstance(sig, str) or not sig:
        return False
    approver = str(approval.get("approver_principal") or "")
    role = str(approval.get("role") or "")
    nonce = str(approval.get("nonce") or "")
    expected = hmac.new(
        CCAS_APPROVAL_KEY.encode("utf-8"),
        _canonical_approval_msg(action_ref, approver, role, nonce, approval.get("expires_at")),
        hashlib.sha256,
    ).hexdigest()
    return hmac.compare_digest(sig, expected)


def _not_expired(approval: Any) -> bool:
    """Fas 2.17 — honor an EXPLICIT expires_at on the approval record.
    Absent => no expiry (documented boundary). Present => must parse (epoch
    seconds or ISO-8601) and lie in the future; malformed => invalid
    (fail-closed). The approval backend decides whether to issue expiries."""
    exp = approval.get("expires_at")
    if exp is None:
        return True
    try:
        if isinstance(exp, (int, float)) and not isinstance(exp, bool):
            deadline = float(exp)
        else:
            from datetime import datetime, timezone
            dt = datetime.fromisoformat(str(exp))
            if dt.tzinfo is None:
                dt = dt.replace(tzinfo=timezone.utc)
            deadline = dt.timestamp()
    except (ValueError, TypeError):
        return False  # malformed expiry — fail closed
    return time.time() < deadline


def _valid_approvals(action: Any) -> list:
    """The structured approval RECORDS that are valid for THIS action. An
    approval only counts when it is a structured record (a bare name counts for
    NOTHING), carries an approver role, is bound to this action's ref, uses a
    not-yet-seen nonce (anti-replay within the set), is NOT expired, is NOT
    already consumed in the persistent ledger (Fas 2.17 — anti-replay ACROSS
    calls: an approval that released an action once can never release another),
    and is signature-verified (fail-closed when CCAS_APPROVAL_KEY is unset)."""
    if not isinstance(action, dict):
        return []
    raw = action.get("approvals")
    if not isinstance(raw, (list, tuple)):
        return []
    action_ref = _action_ref(action)
    if not action_ref:
        return []  # cannot bind approvals to an unidentified action — fail closed
    valid: list = []
    used_nonces: set = set()
    for item in raw:
        if not isinstance(item, dict):
            continue  # bare strings (e.g. "alice") never count
        approver = str(item.get("approver_principal") or "")
        role = str(item.get("role") or "")
        nonce = str(item.get("nonce") or "")
        if not approver or not nonce:
            continue
        if role not in CCAS_APPROVER_ROLES:
            continue  # not an approver role
        if str(item.get("action_ref") or "") != action_ref:
            continue  # not bound to THIS action
        if nonce in used_nonces:
            continue  # replayed nonce (within this request)
        if not _not_expired(item):
            continue  # expired or malformed expiry (fail-closed)
        if approval_ledger.is_consumed(action_ref, approver, nonce):
            continue  # already released an action once (persistent anti-replay)
        if not verify_approval_signature(item, action_ref):
            continue  # unsigned / bad signature / no backend key (fail-closed)
        used_nonces.add(nonce)
        valid.append(item)
    return valid


def dual_approval_trust(action: Any) -> str:
    """How INDEPENDENT the approvers on this action actually are.

    Fas 3.37 (external DD, trust boundary) — SAY WHAT THE QUORUM MEANS.

    tier_4 counts DISTINCT approver principals, which is correct as far as it
    goes. But a single wildcard public key verifies every principal: whoever
    holds that one external private key can produce two principal entries and
    satisfy the quorum alone. That is not necessarily wrong — the key may belong
    to an approval service that authenticates two humans itself — but then the
    guarantee is "two principals attested by ONE external authority", not "two
    cryptographically independent signatories".

    Blocking the wildcard would break a legitimate deployment. Silently calling
    it independent would overclaim. So the posture is stamped on the decision,
    the way every other unprovable-here property is:

      independent_keys  every approver resolved to their OWN registered key
      single_authority  at least one resolved via the wildcard, so one key
                        stands behind more than one principal
      shared_secret     no pubkeys bound at all (HMAC fallback; the agent can
                        mint what it verifies — see approval_trust())
      unbound           no approval backend bound; nothing releases
    """
    pubkeys = _approval_pubkey_map()
    if not pubkeys:
        return "shared_secret" if os.environ.get("CCAS_APPROVAL_KEY") else "unbound"
    named = 0
    wildcarded = 0
    for a in _valid_approvals(action):
        approver = canonical_identity(a.get("approver_principal"))
        if pubkeys.get(approver):
            named += 1
        elif pubkeys.get("*"):
            wildcarded += 1
    if wildcarded:
        return "single_authority"
    return "independent_keys" if named else "unbound"


def _valid_approver_principals(action: Any) -> set:
    """The set of DISTINCT authenticated approver principals whose approvals
    are valid for THIS action (see _valid_approvals). Independence is enforced
    by de-duplicating on approver_principal."""
    return {canonical_identity(a.get("approver_principal")) for a in _valid_approvals(action)}


def _consume_for_release(action: Any, valid: list) -> dict | None:
    """Fas 2.17/2.22 — atomically consume the EXACT valid approval set the tier
    branch decided on, BEFORE a release. Returns None only when THIS call is the
    sole releaser: it durably wrote EVERY tuple in the valid set itself. Any of —
    an empty set, a ledger failure, or one/more tuples already consumed by a
    concurrent or prior release (approval_ledger.consume writes fewer than
    len(valid)) — returns a fail-closed HOLD decision dict. This is what makes an
    approval single-use under concurrency: two callers racing to release the same
    action both pass the tier threshold, but the atomic ledger lets only one of
    them write the tuples, so only that one releases (no double release)."""
    if not valid:
        return {
            "status": "pending",
            "route": "approval_queue",
            "reason": "no fresh approvals to consume — release withheld (single-use, fail-closed)",
        }
    try:
        written = approval_ledger.consume(_action_ref(action), valid)
    except approval_ledger.LedgerUnavailable as e:
        return {
            "status": "pending",
            "route": "approval_queue",
            "reason": "approval ledger unavailable — release withheld (fail-closed): %s" % e,
        }
    if written < len(valid):
        return {
            "status": "pending",
            "route": "approval_queue",
            "reason": "approvals already consumed by a concurrent/prior release — withheld (single-use, fail-closed)",
        }
    return None


