def ccas_decide(action: Any, tier: str) -> dict:
    """Decide, then DISCLOSE the approval posture on every path.

    Fas 3.7 — the trust posture is stamped by this wrapper rather than at each
    return, because the branch that actually released tier_4 was the one that
    got missed when the field was added by hand. A property that must hold on
    every path should be applied on every path, once."""
    clock = clock_trust()
    # DD P0 (fleet) — capability-lease enforcement at the ONE choke point every
    # privileged action already passes (same all-paths principle as Fas 3.7).
    # When this runtime is a fleet member (FLEET_LEASE_REQUIRED truthy) a valid,
    # unexpired, signature-verified capability lease is REQUIRED before any
    # privileged action is even considered; missing/expired/invalid DENIES
    # fail-closed. No development default key exists — a missing key is a deny.
    # DD P0 FTC-3: enforcement is MANDATORY for a fleet-managed member, decided
    # by the runtime's own signed identity (fleet_trust.fleet_managed) — NOT by
    # an operator env flag that no delivered deployment sets. A fleet-managed
    # agent with absent/broken lease infrastructure fail-closes here; the lease
    # is checked for the SPECIFIC capability this action needs (its
    # selected_action name), so a lease scoped to other capabilities does not
    # authorise this one (FTC-2 scope binding, enforced end-to-end).
    from src.shared.fleet_trust import fleet_managed, require_fleet_lease
    if fleet_managed():
        _capability = ""
        if isinstance(action, dict):
            _capability = str(action.get("selected_action") or action.get("name")
                              or action.get("action") or action.get("type") or "")
        _lease_ok, _lease_reasons = require_fleet_lease(_capability)
        if not _lease_ok:
            return {
                "status": "denied",
                "tier": _normalise_tier(tier),
                "route": "fleet_lease_gate",
                "reason": "fleet capability lease invalid or absent for '%s': %s" % (
                    _capability or "<unnamed action>", ", ".join(_lease_reasons)),
                "approval_trust": approval_trust(),
                "clock_trust": clock,
            }
    decision = _ccas_decide(action, tier)
    if isinstance(decision, dict):
        decision.setdefault("approval_trust", approval_trust())
        decision.setdefault("clock_trust", clock)
        # Fas 3.13 — a released decision rests on expires_at, and expires_at
        # rests on the clock. With the clock proven to have moved backwards the
        # freshness verdict is worthless, so the release is withheld rather
        # than granted on evidence we know is unreliable. Refusing here (after
        # the decision, on the wrapper) covers every branch that can release,
        # for the same reason approval_trust is stamped here.
        if clock == "rollback_detected" and decision.get("status") == "approved":
            return {
                "status": "pending",
                "tier": decision.get("tier"),
                "route": "approval_queue",
                "reason": ("clock rollback detected: the system clock reads before the approval "
                           "ledger's high-water mark, so approval freshness (expires_at) cannot "
                           "be judged; release withheld"),
                "approval_trust": decision.get("approval_trust"),
                "clock_trust": clock,
            }
    return decision


def _ccas_decide(action: Any, tier: str) -> dict:
    """Decide whether an action emitted on a Yo port can proceed,
    must wait for analyst approval, must escalate to a human, or — for the
    strictest tier_4 (dual_approval) — must park pending until two independent
    approvals are recorded.

    Fas 2.22: every decision carries "action_ref" — the CONTENT hash the
    approvals are bound to (canonical_action_ref). The executor re-derives it
    before applying the side effect, so the action executed is byte-identical to
    the action approved (no confused deputy at the executor boundary)."""
    canonical = _normalise_tier(tier)
    ref = _action_ref(action)
    # Fas 3.2 — an APPROVAL-BEARING action must be tenant-scoped. A privileged
    # action nobody can attribute to a tenant must not be releasable: without a
    # tenant the approval binds nothing that isolates one customer from another.
    # tier_1 (auto, reversible, no approval) is deliberately unaffected.
    if canonical != TIER_1 and not action_tenant(action):
        return {
            "status": "pending",
            "tier": canonical,
            "route": "hold",
            "action_ref": ref,
            "reason": ("fail-closed: the action carries no tenant_id — a gated action must be "
                       "tenant-scoped before any approval can release it (Fas 3.2)"),
            "approval_trust": approval_trust(),
        }
    if canonical == TIER_1:
        return {
            "status": "approved",
            "tier": canonical,
            "route": "emit",
            "action_ref": ref,
            "reason": "tier_1: auto-execute (low blast radius, reversible)",
            "approval_trust": approval_trust(),
        }
    if canonical == TIER_2:
        valid = _valid_approvals(action)
        approvers = {canonical_identity(a.get("approver_principal")) for a in valid}
        if approvers:
            held = _consume_for_release(action, valid)  # Fas 2.17/2.22: atomic single-use before release
            if held is not None:
                held["tier"] = canonical
                held["action_ref"] = ref
                held["approval_trust"] = approval_trust()
                return held
            return {
                "status": "approved",
                "tier": canonical,
                "route": "emit",
                "action_ref": ref,
                "reason": "tier_2: analyst approval verified (%d provenance-valid, consumed in ledger)" % len(approvers),
                "approvals": len(approvers),
            }
        return {
            "status": "pending",
            "tier": canonical,
            "route": "approval_queue",
            "action_ref": ref,
            "reason": "tier_2: analyst approval required before emit (no provenance-verified approval yet)",
        }
    if canonical == TIER_3:
        # Fas 2.22 (Peter #4) — TIER_3 is "multi-party / admin". A single ORDINARY
        # approver must NOT release it. Release requires EITHER a valid approval
        # from an ADMIN role, OR at least TIER_3_MIN_APPROVALS independent
        # approver identities. This logic is EXECUTABLE here, not a comment.
        valid = _valid_approvals(action)
        principals = {canonical_identity(a.get("approver_principal")) for a in valid}
        admins = {canonical_identity(a.get("approver_principal")) for a in valid
                  if str(a.get("role") or "") in CCAS_ADMIN_ROLES}
        if admins or len(principals) >= TIER_3_MIN_APPROVALS:
            held = _consume_for_release(action, valid)  # Fas 2.17/2.22: atomic single-use before release
            if held is not None:
                held["tier"] = canonical
                held["action_ref"] = ref
                held["approval_trust"] = approval_trust()
                return held
            return {
                "status": "approved",
                "tier": canonical,
                "route": "emit",
                "action_ref": ref,
                "reason": "tier_3: multi-party/admin approval verified (%d independent principal(s)%s, consumed in ledger)"
                          % (len(principals), ", admin sign-off" if admins else ""),
                "approvals": len(principals),
            }
        return {
            "status": "escalated",
            "tier": canonical,
            "route": "escalation_topic",
            "action_ref": ref,
            "reason": "tier_3: multi-party / admin approval required — need an admin approver or >=%d independent approvers (have %d)"
                      % (TIER_3_MIN_APPROVALS, len(principals)),
            "approvals": len(principals),
        }
    if canonical == TIER_4:
        # Strictest tier (TIER_STRICTNESS[TIER_4] == 4). Dual approval: the action
        # NEVER auto-approves and is NEVER dropped — it parks pending in the
        # dual-approval queue until TWO INDEPENDENT approvers have signed. We
        # count distinct approver identities (a single approver, even repeated,
        # is insufficient); only the second independent signature flips it to
        # approved. This logic is EXECUTABLE here, not a comment.
        valid = _valid_approvals(action)
        approvals = _independent_approvals(action)
        if approvals >= TIER_4_REQUIRED_APPROVALS:
            held = _consume_for_release(action, valid)  # Fas 2.17/2.22: atomic single-use before release
            if held is not None:
                held["tier"] = canonical
                held["route"] = "dual_approval_queue"
                held["status"] = "pending_dual_approval"
                held["action_ref"] = ref
                return held
            return {
                "status": "approved",
                "tier": canonical,
                "route": "emit",
                "action_ref": ref,
                "reason": (
                    "tier_4: dual approval satisfied "
                    f"({approvals} independent approvals >= {TIER_4_REQUIRED_APPROVALS}, consumed in ledger)"
                ),
                "approvals": approvals,
                # Fas 3.37 — what the quorum actually guarantees here.
                "dual_approval_trust": dual_approval_trust(action),
            }
        return {
            "status": "pending_dual_approval",
            "tier": canonical,
            "route": "dual_approval_queue",
            "action_ref": ref,
            "reason": (
                "tier_4: dual approval required — "
                f"{approvals}/{TIER_4_REQUIRED_APPROVALS} independent approvals so far"
            ),
            "approvals": approvals,
            "dual_approval_trust": dual_approval_trust(action),
        }
    return {
        "status": "denied",
        "tier": tier,
        "route": "drop",
        "action_ref": ref,
        "reason": f"unknown tier: {tier!r}",
    }


def classify_action(action: Any, default_tier: str = TIER_2) -> str:
    """Best-effort tier classification. Handlers can override with their
    own logic; default policy is conservative (tier_2 — manual gate)."""
    if not isinstance(action, dict):
        return default_tier
    explicit = action.get("ccas_tier") or action.get("tier")
    if explicit:
        return _normalise_tier(str(explicit))
    # Heuristic: a few well-known blast-radius signals
    if action.get("scope") in ("fleet", "global", "tenant_wide"):
        return TIER_3
    if action.get("reversible") is True and action.get("scope") in ("single_host", "single_user"):
        return TIER_1
    return default_tier
